"""Reproducible, versioned dataset build engine.

Wires together the existing splitter and versioning modules to produce a
train/val/test dataset plus split_report.json, provenance.json and
manifest.json — without rewriting the splitter logic.

Known limitation (tracked for Fase E): manifest.json is generated by the
existing ``versioning.dataset_version.save_manifest``, whose SHA-256 hash
loads whole files into memory and is not yet guaranteed deterministic
across runs (timestamp fields, and the manifest possibly hashing itself on
a rebuild). Do not treat manifest.json as a stable fingerprint contract
until Fase E lands.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from archaeosort_dataset_builder.splitter.dataset_splitter import (
    build_split_dataset,
    discover_images_by_class,
    prepare_output_directory,
    save_report,
    validate_ratios,
)
from archaeosort_dataset_builder.versioning.dataset_version import save_manifest


class BuildError(ValueError):
    """Raised when the build configuration or inputs are invalid."""


def _resolve(path: Path | str) -> Path:
    return Path(path).expanduser().resolve()


def build_dataset(
    dataset: Path | str,
    output: Path | str,
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42,
    copy_files: bool = False,
    force: bool = False,
) -> dict[str, Any]:
    """Build a reproducible train/val/test dataset from ``dataset``.

    Steps (matches the ARCHAEOSORT_AGENT_CONTEXT build engine spec):
    1. resolve paths
    2. validate ratios
    3. reject input == output
    4. validate the source dataset exists and is a directory
    5. discover classes (via the existing splitter)
    6. prepare the output directory safely (refuses non-empty without force)
    7. reuse the existing deterministic splitter to build train/val/test
    8. save split_report.json
    9. save provenance.json
    10. generate manifest.json (see module docstring for the Fase E caveat)

    Returns a dict with the resolved paths and the generated report/
    provenance content, so callers (CLI, tests) don't need to re-read the
    files from disk.
    """
    source_dir = _resolve(dataset)
    output_dir = _resolve(output)

    # 2. validate ratios first — cheap, and should fail before touching disk.
    validate_ratios(train_ratio, val_ratio, test_ratio)

    # 3. reject input == output BEFORE any destructive step. This must run
    # before prepare_output_directory, which can rmtree the output dir when
    # --force is set — if output == dataset that would delete the source.
    if source_dir == output_dir:
        raise BuildError(
            "The output directory must be different from the source dataset "
            f"directory (both resolved to {source_dir})."
        )

    # 4. validate the source explicitly (discover_images_by_class only
    # checks existence, not that it's a directory).
    if not source_dir.exists():
        raise FileNotFoundError(f"Dataset not found: {source_dir}")

    if not source_dir.is_dir():
        raise NotADirectoryError(f"Dataset path is not a directory: {source_dir}")

    # 5. discover classes (raises ValueError if no classified images found).
    images_by_class = discover_images_by_class(source_dir)

    # 6. prepare the output directory (raises FileExistsError unless force).
    prepare_output_directory(output_dir, force)

    # 7. build the split using the existing, reusable splitter.
    split_report = build_split_dataset(
        images_by_class=images_by_class,
        output_dir=output_dir,
        train_ratio=train_ratio,
        val_ratio=val_ratio,
        seed=seed,
        copy_files=copy_files,
    )

    # 8. persist split_report.json
    split_report_path = save_report(split_report, output_dir)

    # 9. persist provenance.json
    provenance = {
        "created": datetime.now(UTC).isoformat(),
        "source_dataset": str(source_dir),
        "output_dataset": str(output_dir),
        "seed": seed,
        "mode": "copy" if copy_files else "hardlink_or_copy",
        "ratios": {
            "train": train_ratio,
            "val": val_ratio,
            "test": test_ratio,
        },
        "classes": sorted(images_by_class),
        "source_image_count": sum(len(paths) for paths in images_by_class.values()),
    }
    provenance_path = output_dir / "provenance.json"
    with provenance_path.open("w", encoding="utf-8") as file:
        json.dump(provenance, file, indent=4, ensure_ascii=False)

    # 10. generate manifest.json / fingerprint (existing implementation).
    save_manifest(output_dir)
    manifest_path = output_dir / "manifest.json"

    return {
        "source_dir": source_dir,
        "output_dir": output_dir,
        "split_report": split_report,
        "split_report_path": split_report_path,
        "provenance": provenance,
        "provenance_path": provenance_path,
        "manifest_path": manifest_path,
    }
